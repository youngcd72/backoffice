CREATE SEQUENCE SQ_TB_DSPT_EXEC_L_DSPT_EXEC_SN START WITH 1 INCREMENT BY 1;

CREATE TABLE TB_DSPT_EXEC_L (
    DSPT_EXEC_SN          BIGINT       NOT NULL,
    JOB_ID                VARCHAR(100) NOT NULL,
    JOB_EXEC_ID           BIGINT,
    EXEC_CLS_CD           VARCHAR(1)   NOT NULL,
    EXEC_STAT_CD          VARCHAR(20)  NOT NULL,
    EXEC_ST_DTTM          TIMESTAMP    NOT NULL,
    EXEC_END_DTTM         TIMESTAMP,
    PROC_CNT              BIGINT       NOT NULL DEFAULT 0,
    SUCC_CNT              BIGINT       NOT NULL DEFAULT 0,
    FAIL_CNT              BIGINT       NOT NULL DEFAULT 0,
    ERR_MSG_CONT          VARCHAR(4000),
    EXEC_SRV_NM           VARCHAR(100),
    FIRS_REGR_ID          VARCHAR(10)  NOT NULL,
    FIRS_REG_DT           TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FINA_REGR_ID          VARCHAR(10)  NOT NULL,
    FINA_REG_DT           TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT TB_DSPT_EXEC_L_PK PRIMARY KEY (DSPT_EXEC_SN),
    CONSTRAINT TB_DSPT_EXEC_L_FK01 FOREIGN KEY (JOB_ID) REFERENCES TB_DSPT_JOB_M (JOB_ID)
);

CREATE INDEX TB_DSPT_EXEC_L_IX01 ON TB_DSPT_EXEC_L (JOB_ID, EXEC_ST_DTTM);
CREATE INDEX TB_DSPT_EXEC_L_IX02 ON TB_DSPT_EXEC_L (JOB_EXEC_ID);
CREATE INDEX TB_DSPT_EXEC_L_IX03 ON TB_DSPT_EXEC_L (EXEC_ST_DTTM);

COMMENT ON TABLE  TB_DSPT_EXEC_L IS '배치실행내역';
COMMENT ON COLUMN TB_DSPT_EXEC_L.DSPT_EXEC_SN           IS '배치실행일련번호';
COMMENT ON COLUMN TB_DSPT_EXEC_L.JOB_ID                 IS '직무ID';
COMMENT ON COLUMN TB_DSPT_EXEC_L.JOB_EXEC_ID            IS '직무실행ID (BATCH_JOB_EXECUTION.JOB_EXECUTION_ID, SKIP/기동실패 건은 NULL)';
COMMENT ON COLUMN TB_DSPT_EXEC_L.EXEC_CLS_CD            IS '실행구분코드 (S 스케줄, M 수동, R 재시작)';
COMMENT ON COLUMN TB_DSPT_EXEC_L.EXEC_STAT_CD           IS '실행상태코드 (STARTED, COMPLETED, FAILED, STOPPED, ABANDONED, SKIP)';
COMMENT ON COLUMN TB_DSPT_EXEC_L.EXEC_ST_DTTM           IS '실행시작일시';
COMMENT ON COLUMN TB_DSPT_EXEC_L.EXEC_END_DTTM          IS '실행종료일시';
COMMENT ON COLUMN TB_DSPT_EXEC_L.PROC_CNT               IS '처리건수';
COMMENT ON COLUMN TB_DSPT_EXEC_L.SUCC_CNT               IS '성공건수';
COMMENT ON COLUMN TB_DSPT_EXEC_L.FAIL_CNT               IS '실패건수';
COMMENT ON COLUMN TB_DSPT_EXEC_L.ERR_MSG_CONT           IS '오류메시지내용';
COMMENT ON COLUMN TB_DSPT_EXEC_L.EXEC_SRV_NM            IS '실행서버명 (Quartz instanceId)';
COMMENT ON COLUMN TB_DSPT_EXEC_L.FIRS_REGR_ID           IS '최초등록자ID';
COMMENT ON COLUMN TB_DSPT_EXEC_L.FIRS_REG_DT            IS '최초등록일시';
COMMENT ON COLUMN TB_DSPT_EXEC_L.FINA_REGR_ID           IS '최종등록자ID';
COMMENT ON COLUMN TB_DSPT_EXEC_L.FINA_REG_DT            IS '최종등록일시';
